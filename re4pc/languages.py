# IDs follow the engine's Load_LangData resource table (jp, e, f, s, i, g).
GAME_LANGUAGES = {'en': 'English', 'es': 'Español', 'fr': 'Français',
                  'de': 'Deutsch', 'it': 'Italiano', 'ja': '日本語',
                  'saved': "Use game's saved language"}
GAME_LANGUAGE_IDS = {'ja': 0, 'en': 1, 'fr': 2, 'es': 3, 'it': 4, 'de': 5}
LAUNCHER_LANGUAGES = {code: label for code, label in GAME_LANGUAGES.items() if code != 'saved'}


def apply_game_language(arm, language):
    """Select before title resources load; saved leaves engine user data alone."""
    if language == 'saved':
        return
    identity = GAME_LANGUAGE_IDS[language]
    user = arm.symbols['_ZZN13Bio4_UserData11GetInstanceEvE4inst']
    arm.call('_ZN13Bio4_UserData9SetLangIdEh', user, identity)


