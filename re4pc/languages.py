_PATTERNS = []
for source in TEMPLATES:
    parts = re.split(r'(\{\w+\})', source)
    pattern = ''.join('(?P<' + p[1:-1] + '>.+?)' if p.startswith('{') else re.escape(p) for p in parts)
    _PATTERNS.append((re.compile(pattern, re.DOTALL), source))


def translate(text, language='en'):
    if language not in CATALOGS or not isinstance(text, str):
        return text
    catalog = CATALOGS[language]
    if text in catalog:
        return catalog[text]
    for pattern, source in _PATTERNS:
        match = pattern.fullmatch(text)
        if match:
            return TEMPLATE_CATALOGS[language][source].format(**{key: translate(value, language) for key, value in match.groupdict().items()})
    if '\n' in text:
        return '\n'.join(translate(line, language) for line in text.split('\n'))
    if ': ' in text:
        prefix, detail = text.split(': ', 1)
        if prefix in catalog:
            return catalog[prefix] + ': ' + detail
    return text


def widget_translate(widget, text):
    app = getattr(widget.winfo_toplevel(), 'launcher', None)
    return app.tr(text) if app is not None else text
